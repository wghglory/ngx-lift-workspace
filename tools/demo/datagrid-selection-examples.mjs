// Keep the playground's displayed source identical to the runnable consumer files.
import {readFileSync, writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import prettier from 'prettier';

const root = resolve(import.meta.dirname, '../..');
const directory = resolve(root, 'apps/demo/src/app/clr-lib/pages/datagrid-selection');
const examples = {
  multiple: 'simple-multiple.component',
  single: 'simple-single.component',
  policy: 'data-service-policy-form.component',
  picker: 'organization-picker.component',
  pickerParent: 'picker-parent.component',
  model: 'template-driven.component',
  asyncSubmit: 'async-submit.component',
};
const declarations = [];
for (const [name, file] of Object.entries(examples)) {
  for (const [suffix, extension] of [
    ['Ts', 'ts'],
    ['Html', 'html'],
  ]) {
    declarations.push(
      `export const ${name}${suffix} = ${JSON.stringify(readFileSync(resolve(directory, `${file}.${extension}`), 'utf8'))};`,
    );
  }
}
const options = await prettier.resolveConfig(resolve(directory, 'example-source.ts'));
const generated = await prettier.format(
  '// Generated by tools/demo/datagrid-selection-examples.mjs --write.\n' + declarations.join('\n') + '\n',
  {...options, parser: 'typescript'},
);
const destination = resolve(directory, 'example-source.ts');
if (process.argv.includes('--write')) writeFileSync(destination, generated);
else if (readFileSync(destination, 'utf8') !== generated)
  throw new Error(
    'Datagrid selection source differs from the live examples. Run node tools/demo/datagrid-selection-examples.mjs --write.',
  );
console.log('Datagrid selection: all displayed sources match their runnable files.');
